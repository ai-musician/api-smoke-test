# TC-20 — /apldlr concurrent appliance-upgrade stress (all pkg types)
#
# Models the realistic case where many appliances upgrade packages at roughly
# the same time (e.g., a coordinated rollout, or simply a large fleet polling
# on similar schedules). Each VU performs the full per-appliance upgrade flow:
#
#     1) GET /apldlr/v1/images/<pkgtype>                          (list)
#     2) GET /apldlr/v1/images/<pkgtype>/<filename>?upgradetype=full  (download)
#
# and then loops for the duration. Unlike TC-19 (10 download VUs), this test
# drives high concurrency on the download path to surface bandwidth, pod
# saturation, and artifactservice backpressure under fleet-scale upgrades.
#
# Sub-runs (each N VUs × duration, full list+download flow per VU):
#   A — urldb only
#   B — threat-feed only
#   C — mixed across all available pkg types (round-robin assignment)
#   D — swg only
#   E — virtual only  (user-facing name: "software"; full VPE upgrade tarball,
#                      typically the largest of the 5 — likely to push p95
#                      above the placeholder SLO)
#   F — content only
#
# A sub-run is skipped automatically if its pkg type is not present on
# artifactservice. C runs whenever ≥2 types are available.
#
# SLOs (full list+download flow):
#   p95 < 90 s, success >= 99.0%
#   (placeholder; expected to be retuned per pkgtype once first-run sizes
#    are recorded — software in particular will likely need a higher p95.)
# ---------------------------------------------------------------------------


# Per-sub-run-letter pkgtype map. Reuses TC-19's _TC19_PKGTYPES list for
# consistency, so adding/removing a pkg type in TC-19 propagates here.
_TC20_PKGTYPES = list(_TC19_PKGTYPES)


# Display label for sub-runs whose route pkgtype name differs from the
# user-facing name. The route uses "virtual"; the team refers to it as
# "software" (the vpe-upgrade-sf-* artifact).
_TC20_DISPLAY_NAME = {"virtual": "software"}


_TC20_PER_TYPE_SUBRUNS = [
   ("A", "urldb"),
   ("B", "threat-feed"),
   # C is the mixed sub-run; handled separately below.
   ("D", "swg"),
   ("E", "virtual"),
   ("F", "content"),
]




async def tc20_apldlr_concurrent_upgrades_benchmark(
   concurrency: int = 50, duration: int = 600
) -> None:
   """
   High-concurrency upgrade stress for /apldlr/v1/images/{urldb,threat-feed}.


   Simulates many appliances upgrading the same content package types at
   once. Each VU repeatedly runs list -> download for the duration.
   """
   print(f"\n{'=' * 12} TC-20: apldlr Concurrent Upgrade Stress {'=' * 12}")


   auth_pairs = _get_auth_pairs()
   if not auth_pairs:
       print("  [SKIP] TC-20: no credentials — set LICENSE_KEY+SERIAL, or use "
             "--remote-host / --credential-host (auto-detects from VPE).")
       return
   print(f"  [credentials] {len(auth_pairs)} (license, serial) pair(s) available; "
         f"each VU stays sticky to one pair.")


   conn = _make_connector(concurrency + 1)
   async with aiohttp.ClientSession(
       connector=conn,
       cookie_jar=aiohttp.DummyCookieJar(),
   ) as s:


       # Discover the latest filename per package type.
       latest: dict[str, str] = {}
       for pkgtype in _TC20_PKGTYPES:
           entries = await _tc19_discover_versions(s, pkgtype)
           if entries and entries[0].get("filename"):
               latest[pkgtype] = entries[0]["filename"]
               print(f"  [apldlr] {pkgtype}: latest = {entries[0].get('version', '?')} "
                     f"({entries[0]['filename']})")
           else:
               print(f"  [apldlr] {pkgtype}: no packages found (skipping)")


       if not latest:
           print("  [SKIP] TC-20: no urldb or threat-feed packages available")
           return


       def _params_for(vu_id: int) -> dict:
           pair = auth_pairs[vu_id % len(auth_pairs)]
           return {"platform": "virtual", "license": pair["license"], "serial": pair["serial"]}


       async def _upgrade_once(pkgtype: str, filename: str, base_params: dict,
                               m: RunMetrics) -> None:
           """One full upgrade flow: list then download. Records latency for the whole flow."""
           t = time.perf_counter()
           try:
               async with s.get(
                   f"{GATEWAY_URL}/apldlr/v1/images/{pkgtype}",
                   params=base_params,
               ) as r:
                   await r.read()
                   if r.status != 200:
                       m.record(time.perf_counter() - t, r.status)
                       return
               params = {**base_params, "upgradetype": "full"}
               async with s.get(
                   f"{GATEWAY_URL}/apldlr/v1/images/{pkgtype}/{filename}",
                   params=params,
               ) as r:
                   await r.read()
                   m.record(time.perf_counter() - t, r.status)
           except Exception:
               m.record(time.perf_counter() - t, 0)


       async def _run_sub(label: str, pkg_assignments: list[str]) -> None:
           """Run a sub-run where each VU is pinned to a pkgtype from pkg_assignments."""
           m = RunMetrics()


           async def _worker(vu_id: int, pkgtype: str, end: float) -> None:
               filename = latest[pkgtype]
               base_params = _params_for(vu_id)
               while time.time() < end:
                   await _upgrade_once(pkgtype, filename, base_params, m)


           end = time.time() + duration
           await asyncio.gather(*[
               asyncio.create_task(_worker(i, pkg, end))
               for i, pkg in enumerate(pkg_assignments)
           ])
           m.print_report(label, duration)
           m.assert_slo(p95_ms=90000.0, success_pct=99.0)


       # ----------------------------------------------------------------
       # Sub-runs A and B: per-pkgtype (urldb, threat-feed) — kept first
       # for backward-compatibility with prior runs.
       # ----------------------------------------------------------------
       for letter, pkg in _TC20_PER_TYPE_SUBRUNS[:2]:
           display = _TC20_DISPLAY_NAME.get(pkg, pkg)
           if pkg in latest:
               print(f"\n  Sub-run {letter}: {concurrency} concurrent {display} "
                     f"upgrades, {duration}s")
               await _run_sub(
                   f"TC-20{letter}: {display} concurrent upgrades",
                   [pkg] * concurrency,
               )
               await asyncio.sleep(3)
           else:
               print(f"\n  Sub-run {letter}: [SKIP] {display} not available")


       # ----------------------------------------------------------------
       # Sub-run C: Mixed — split VUs evenly across all available pkgtypes
       # ----------------------------------------------------------------
       available = [p for p in _TC20_PKGTYPES if p in latest]
       if len(available) >= 2:
           split = [available[i % len(available)] for i in range(concurrency)]
           counts = {_TC20_DISPLAY_NAME.get(p, p): split.count(p) for p in available}
           mix_label = "+".join(_TC20_DISPLAY_NAME.get(p, p) for p in available)
           print(f"\n  Sub-run C: {concurrency} concurrent mixed upgrades, {duration}s "
                 f"(split: {counts})")
           await _run_sub(
               f"TC-20C: mixed {mix_label} concurrent upgrades",
               split,
           )
           await asyncio.sleep(3)
       else:
           print("\n  Sub-run C: [SKIP] need ≥2 pkg types for mixed run")


       # ----------------------------------------------------------------
       # Sub-runs D, E, F: per-pkgtype (swg, virtual/software, content) —
       # newly visible on perf01 artifactservice.
       # ----------------------------------------------------------------
       for letter, pkg in _TC20_PER_TYPE_SUBRUNS[2:]:
           display = _TC20_DISPLAY_NAME.get(pkg, pkg)
           if pkg in latest:
               print(f"\n  Sub-run {letter}: {concurrency} concurrent {display} "
                     f"upgrades, {duration}s")
               await _run_sub(
                   f"TC-20{letter}: {display} concurrent upgrades",
                   [pkg] * concurrency,
               )
               if letter != _TC20_PER_TYPE_SUBRUNS[-1][0]:
                   await asyncio.sleep(3)
           else:
               print(f"\n  Sub-run {letter}: [SKIP] {display} not available")




