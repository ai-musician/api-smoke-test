def _random_metrics_payload() -> bytes:
  """Return a valid metrics payload (list of metric dicts) for the callhome metrics endpoint."""
  ts = int(time.time())
  metrics = [
      {"key": "package_version", "value": "1.0.0"},
      {"key": "platform-modes", "value": f"mode-{secrets.token_hex(4)}"},
      {"key": "timestamp", "value": str(ts)},
      {"key": "tag", "value": secrets.token_hex(8)},
      {"key": "serial", "value": SERIAL},
      {"key": "tenant_id", "value": TENANT_ID},
  ]
  return json.dumps(metrics).encode()








async def _authenticate(session: aiohttp.ClientSession) -> str | None:
  """POST /callhome/authenticate and return NS_PERSIST cookie value."""
  try:
      async with session.post(
          f"{GATEWAY_URL}/callhome/authenticate",
          json={"ui_hostname": UI_HOSTNAME, "rest_token": REST_TOKEN},
      ) as resp:
          await resp.read()
          # read from Set-Cookie header directly so this works with DummyCookieJar
          for set_cookie in resp.headers.getall("Set-Cookie", []):
              for part in set_cookie.split(";"):
                  part = part.strip()
                  if part.startswith("NS_PERSIST="):
                      return part[len("NS_PERSIST="):]
          # fallback: read from session cookie jar if not using DummyCookieJar
          for cookie in session.cookie_jar:
              if cookie.key == "NS_PERSIST":
                  return cookie.value
  except Exception as exc:
      print(f"  [warn] initial authenticate failed: {exc}")
  return None








