async def _tc02_worker(url: str, ssl_ctx: ssl.SSLContext, m: RunMetrics, end: float) -> None:
  while time.time() < end:
      t = time.perf_counter()
      try:
          # New connector per request = new TLS handshake each time
          conn = aiohttp.TCPConnector(limit=1, ssl=ssl_ctx, force_close=True)
          async with aiohttp.ClientSession(connector=conn) as s:
              async with s.get(url) as r:
                  await r.read()
                  m.record(time.perf_counter() - t, r.status)
      except Exception:
          m.record(time.perf_counter() - t, 0)








