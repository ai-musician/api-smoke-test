async def tc04_auth_hot(concurrency: int = 50, duration: int = 900) -> RunMetrics:
  m    = RunMetrics()
  stop = asyncio.Event()
  # authenticate in a throwaway session to get the cookie
  async with aiohttp.ClientSession(connector=_make_connector(1),
                                   cookie_jar=aiohttp.DummyCookieJar()) as auth_s:
      cookie = await _authenticate(auth_s)
  if not cookie:
      print("  [SKIP] TC-04: could not obtain NS_PERSIST cookie")
      return m
  # run workers in a fresh session with no cookie jar so only our explicit
  # Cookie header is sent — prevents stale jar entries causing 401s
  conn = _make_connector(concurrency)
  async with aiohttp.ClientSession(connector=conn,
                                   cookie_jar=aiohttp.DummyCookieJar()) as s:
      end = time.time() + duration
      obs = asyncio.create_task(_run_observer("TC-04: Auth Hot Path (Cookie Reuse)", stop_event=stop))
      await asyncio.gather(*[asyncio.create_task(_tc04_worker(s, cookie, m, end))
                              for _ in range(concurrency)])
      stop.set()
      await obs
  m.print_report("TC-04: Auth Hot Path (Cookie Reuse)", duration)
  _print_error_breakdown(m, "TC-04: Auth Hot Path (Cookie Reuse)")
  m.assert_slo(p95_ms=100.0, success_pct=99.9, max_timeout_pct=0.1)
  return m








