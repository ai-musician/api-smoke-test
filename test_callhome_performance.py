STATUS_CAUSES: dict[int, tuple[str, str]] = {
  401: ("Auth misconfig, expired cookie, missing mTLS cert",
        "Usually test-harness bug; do not count toward SLO unless intentional"),
  403: ("Auth misconfig, expired cookie, missing mTLS cert",
        "Usually test-harness bug; do not count toward SLO unless intentional"),
  413: ("client_max_body_size hit",
        "Expected in TC-07 Sub-run D; unexpected elsewhere = misconfig"),
  499: ("Client closed before response",
        "LG timeout too short or severe gateway slowness"),
  502: ("Upstream refused/unreachable",
        "Gateway-to-upstream problem"),
  503: ("Nginx-side refusal (overload, drained pod)",
        "Gateway capacity issue; counts toward SLO"),
  504: ("Upstream response timeout",
        "Upstream slow or timeout too tight"),
}








def _error_breakdown(m: "RunMetrics", scenario: str) -> dict:
  """Return structured error breakdown and write it to the artifact dir."""
  breakdown: list[dict] = []
  for code, count in sorted(m.by_status.items()):
      if code < 400 and code != 0:
          continue
      cause, action = STATUS_CAUSES.get(code, ("Unknown", "Investigate"))
      breakdown.append({
          "status_code": code,
          "count": count,
          "likely_cause": cause,
          "action": action,
      })
  result = {"scenario": scenario, "errors": breakdown}
  d = _artifact_dir(scenario)
  with open(d / "error_breakdown.json", "w") as fh:
      json.dump(result, fh, indent=2)
  return result








def _print_error_breakdown(m: "RunMetrics", scenario: str) -> None:
  bd = _error_breakdown(m, scenario)
  errors = [e for e in bd["errors"] if e["count"] > 0]
  if not errors:
      return
  print(f"\n  Error breakdown:")
  for e in errors:
      print(f"    {e['status_code']:>3} × {e['count']:>6}  {e['likely_cause']}")
      print(f"           Action: {e['action']}")








def _lg_host_snapshot() -> dict:
  """Capture LG host CPU, NIC tx/rx bytes/s, socket count (best-effort)."""
  import subprocess




  snap: dict = {}
  try:
      # CPU: use /proc/stat (Linux) or fall back silently
      out = subprocess.check_output(
          ["sh", "-c",
           "cat /proc/stat 2>/dev/null | awk '/^cpu / {idle=$5; total=0; for(i=2;i<=NF;i++) total+=$i; printf \"%.2f\", (1-idle/total)*100}'"],
          timeout=2, stderr=subprocess.DEVNULL,
      )
      snap["cpu_pct"] = float(out.strip()) if out.strip() else None
  except Exception:
      snap["cpu_pct"] = None




  try:
      # NIC rx/tx: sum all non-lo interfaces from /proc/net/dev
      out = subprocess.check_output(
          ["sh", "-c",
           "cat /proc/net/dev 2>/dev/null | awk 'NR>2 && !/lo:/ {rx+=$2; tx+=$10} END {print rx, tx}'"],
          timeout=2, stderr=subprocess.DEVNULL,
      ).decode()
      parts = out.split()
      if len(parts) == 2:
          snap["nic_rx_bytes"] = int(parts[0])
          snap["nic_tx_bytes"] = int(parts[1])
  except Exception:
      snap["nic_rx_bytes"] = None
      snap["nic_tx_bytes"] = None




  try:
      # Socket count: established TCP connections
      out = subprocess.check_output(
          ["sh", "-c", "ss -tnH state established 2>/dev/null | wc -l"],
          timeout=2, stderr=subprocess.DEVNULL,
      )
      snap["established_sockets"] = int(out.strip())
  except Exception:
      snap["established_sockets"] = None




  snap["ts"] = time.time()
  return snap








async def _run_observer(scenario: str, interval: float = 1.0,
                      stop_event: asyncio.Event | None = None) -> list[dict]:
  """
  Background coroutine: samples LG host stats and kubectl top pods every
  `interval` seconds until stop_event is set.  Writes
  perf-runs/.../observer_samples.jsonl when done.
  """
  import subprocess




  samples: list[dict] = []
  d = _artifact_dir(scenario)
  stop = stop_event or asyncio.Event()




  while not stop.is_set():
      snap = _lg_host_snapshot()
      # kubectl top pods — non-fatal; skip if kubectl not on PATH
      try:
          out = subprocess.check_output(
              ["kubectl", "top", "pods", "-n", "risk-insights",
               "--no-headers", "--sort-by=cpu"],
              timeout=5, stderr=subprocess.DEVNULL,
          ).decode()
          snap["kubectl_top"] = out.strip()
      except Exception:
          snap["kubectl_top"] = None




      samples.append(snap)
      try:
          await asyncio.wait_for(asyncio.shield(stop.wait()), timeout=interval)
      except asyncio.TimeoutError:
          pass




  # Write JSONL
  with open(d / "observer_samples.jsonl", "w") as fh:
      for s in samples:
          fh.write(json.dumps(s) + "\n")




  return samples








