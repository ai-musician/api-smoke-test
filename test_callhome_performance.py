@dataclass
class RunMetrics:
  latencies: list[float] = field(default_factory=list)
  success:   int = 0
  errors:    int = 0
  by_status: dict[int, int] = field(default_factory=dict)




  def record(self, latency: float, status: int) -> None:
      self.latencies.append(latency)
      self.by_status[status] = self.by_status.get(status, 0) + 1
      if 200 <= status < 300:
          self.success += 1
      else:
          self.errors += 1




  def total(self) -> int:
      return self.success + self.errors




  def pct(self, p: int) -> float:
      if not self.latencies:
          return 0.0
      return statistics.quantiles(sorted(self.latencies), n=100)[p - 1] * 1000




  def to_json(self, name: str, duration: float) -> dict:
      total = self.total()
      rps   = total / max(duration, 0.001)
      sr    = (self.success / max(total, 1)) * 100
      by_status_str = {str(k): v for k, v in self.by_status.items()}
      d: dict = {
          "name": name,
          "duration_s": round(duration, 3),
          "total_requests": total,
          "success_rate_pct": round(sr, 4),
          "throughput_rps": round(rps, 3),
          "status_codes": by_status_str,
      }
      if self.latencies:
          d.update({
              "p50_ms":  round(self.pct(50), 3),
              "p90_ms":  round(self.pct(90), 3),
              "p95_ms":  round(self.pct(95), 3),
              "p99_ms":  round(self.pct(99), 3),
              "max_ms":  round(max(self.latencies) * 1000, 3),
          })
      return d




  def save(self, name: str, duration: float) -> None:
      d    = _artifact_dir(name)
      data = self.to_json(name, duration)
      path = d / "run_metrics.json"
      with open(path, "w") as fh:
          json.dump(data, fh, indent=2)




  def print_report(self, name: str, duration: float) -> None:
      total = self.total()
      rps = total / max(duration, 0.001)
      sr  = (self.success / max(total, 1)) * 100
      print(f"\n{'=' * 12} {name} {'=' * 12}")
      print(f"  Duration:     {duration:.1f}s")
      print(f"  Total Req:    {total}")
      print(f"  Success Rate: {sr:.2f}%")
      print(f"  Throughput:   {rps:.1f} req/s")
      print(f"  Status Codes: {json.dumps(self.by_status)}")
      if self.latencies:
          print(f"  p50:  {self.pct(50):.2f} ms")
          print(f"  p90:  {self.pct(90):.2f} ms")
          print(f"  p95:  {self.pct(95):.2f} ms")
          print(f"  p99:  {self.pct(99):.2f} ms")
          print(f"  max:  {max(self.latencies) * 1000:.2f} ms")
      self.save(name, duration)




  def assert_slo(self, *, p95_ms: float | None = None, p99_ms: float | None = None,
                 success_pct: float = 99.9,
                 max_timeout_pct: float | None = None) -> bool:
      total = self.total()
      sr = (self.success / max(total, 1)) * 100
      ok = True
      if sr < success_pct:
          print(f"  FAIL  success rate {sr:.2f}% < {success_pct}%")
          ok = False
      if p95_ms is not None and self.latencies:
          actual = self.pct(95)
          if actual > p95_ms:
              print(f"  FAIL  p95 {actual:.2f} ms > {p95_ms} ms")
              ok = False
      if p99_ms is not None and self.latencies:
          actual = self.pct(99)
          if actual > p99_ms:
              print(f"  FAIL  p99 {actual:.2f} ms > {p99_ms} ms")
              ok = False
      if max_timeout_pct is not None:
          timeouts = self.by_status.get(502, 0) + self.by_status.get(503, 0)
          timeout_rate = (timeouts / max(total, 1)) * 100
          if timeout_rate > max_timeout_pct:
              print(f"  FAIL  502/503 rate {timeout_rate:.3f}% > {max_timeout_pct}%")
              ok = False
      if ok:
          print(f"  PASS")
      return ok








