async def tc_vpe01_event_rate(concurrency: int = 50,
                             duration: int = 600) -> RunMetrics:
  """
  VPE Beta event-rate baseline (TC-VPE-01).
  Drives callhome metrics endpoint at VPE peak load (500 CPS equivalent)
  and checks all four VPE success criteria.
  For the full 6-hour endurance run: duration=21600 (or pass VPE_ENDURANCE_H * 3600).
  """
  m       = RunMetrics()
  thirds  = duration // 3
  early_m = RunMetrics()
  late_m  = RunMetrics()




  conn = _make_connector(concurrency + 1)
  async with aiohttp.ClientSession(connector=conn) as s:
      cookie = await _authenticate(s)
      if not cookie:
          print("  [SKIP] TC-VPE-01: could not obtain NS_PERSIST cookie")
          return m




      start = time.time()
      end_t = start + duration




      # Collect early and late sub-windows for growing-latency detection
      async def _worker() -> None:
          headers = {"Cookie": f"NS_PERSIST={cookie}", "Content-Type": "application/json"}
          while time.time() < end_t:
              payload = _random_metrics_payload()
              t = time.perf_counter()
              elapsed = time.time() - start
              try:
                  async with s.post(
                      f"{GATEWAY_URL}/callhome/metrics/{VPE_TENANT_ID}/{SERIAL}",
                      data=payload,
                      headers=headers,
                  ) as r:
                      await r.read()
                      lat = time.perf_counter() - t
                      status = r.status
              except Exception as exc:
                  lat = time.perf_counter() - t
                  status = 0
              m.record(lat, status)
              if elapsed < thirds:
                  early_m.record(lat, status)
              elif elapsed >= duration - thirds:
                  late_m.record(lat, status)




      await asyncio.gather(*[asyncio.create_task(_worker())
                              for _ in range(concurrency)])




  m.print_report("TC-VPE-01: VPE Beta Event-Rate Baseline", duration)




  # VPE criterion 4: no growing latency — late-window p90 must not exceed
  # early-window p90 by more than 20%
  growing_latency = False
  if early_m.latencies and late_m.latencies:
      early_p90 = early_m.pct(90)
      late_p90  = late_m.pct(90)
      growth    = ((late_p90 - early_p90) / max(early_p90, 0.001)) * 100
      print(f"  Latency growth check: early p90={early_p90:.1f}ms  "
            f"late p90={late_p90:.1f}ms  delta={growth:+.1f}%")
      if growth > 20.0:
          print(f"  FAIL  growing latency: p90 grew {growth:.1f}% (threshold 20%)")
          growing_latency = True




  slo_ok = m.assert_slo(success_pct=99.0, max_timeout_pct=VPE_TIMEOUT_SLO)
  if not slo_ok or growing_latency:
      print("  OVERALL: FAIL")
  else:
      print("  OVERALL: PASS")
  print(f"  [manual check] kubectl top pods -n risk-insights — CPU/mem must be <{VPE_CPU_MEM_SLO}%")
  return m








