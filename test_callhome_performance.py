async def tc03_auth_cold(concurrency: int = 50, duration: int = 300) -> RunMetrics:
  m = RunMetrics()
  # Ramp: 10 → concurrency over 10 % of duration, then hold
  ramp_end = time.time() + max(30, duration // 10)
  conn = _make_connector(concurrency)
  stop = asyncio.Event()
  async with aiohttp.ClientSession(connector=conn) as s:
      end = time.time() + duration
      obs = asyncio.create_task(_run_observer("TC-03: Authenticate-Heavy (Cold Path)", stop_event=stop))
      initial = max(10, concurrency // 5)
      tasks = [asyncio.create_task(_tc03_worker(s, m, end)) for _ in range(initial)]
      await asyncio.sleep(min(30, time.time() - ramp_end + 30))
      tasks += [asyncio.create_task(_tc03_worker(s, m, end))
                for _ in range(concurrency - initial)]
      await asyncio.gather(*tasks)
      stop.set()
      await obs
  m.print_report("TC-03: Authenticate-Heavy (Cold Path)", duration)
  _print_error_breakdown(m, "TC-03: Authenticate-Heavy (Cold Path)")
  m.assert_slo(p95_ms=500.0, success_pct=99.9)
  return m








