def _make_upload_body(size_mb: float) -> bytes:
  size = int(size_mb * 1024 * 1024)
  # Small random header so sequential uploads aren't identical
  noise = secrets.token_bytes(64)
  fill  = b"\xAB" * (size - len(noise))
  return noise + fill








