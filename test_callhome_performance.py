def _fetch_credentials_from_vpe(host: str, user: str, key: str | None,
                               port: int, sshpass_prefix: list[str],
                               ssh_opts: list[str]) -> dict[str, str] | None:
   """SSH into a VPE and read its license_key + serial. Returns {'license','serial'} or None.


   Used to build a multi-VPE CREDENTIAL_POOL for TC-19/TC-20. License comes
   from /opt/ns/cfg/cfgagent.conf, serial from /opt/ns/cloud/serial.
   """
   target = f"{user}@{host}"
   cmd = (
       "cat /opt/ns/cloud/serial; echo '---';"
       "python3 -c \""
       "import re; "
       "m = re.search(r'^license_key: (.+)', open('/opt/ns/cfg/cfgagent.conf').read(), re.MULTILINE); "
       "print(m.group(1).strip() if m else '')"
       "\""
   )
   try:
       result = subprocess.run(
           sshpass_prefix + ["ssh"] + ssh_opts + [target, cmd],
           capture_output=True, text=True, check=True,
       )
   except subprocess.CalledProcessError as e:
       print(f"  [warn] could not fetch credentials from {host}: {e.stderr.strip()}")
       return None


   parts = result.stdout.strip().split("---")
   if len(parts) < 2:
       print(f"  [warn] unexpected output from {host}: {result.stdout!r}")
       return None


   serial_raw = parts[0].strip()
   try:
       serial = json.loads(serial_raw).get("serial", serial_raw)
   except (json.JSONDecodeError, ValueError):
       serial = serial_raw
   license_key = parts[1].strip()


   if not serial or not license_key:
       print(f"  [warn] {host}: missing serial or license_key (serial={bool(serial)}, "
             f"license={bool(license_key)})")
       return None
   return {"license": license_key, "serial": serial}




def _run_remote(host: str, user: str, scenarios: list[str],
               key: str | None, port: int,
               credential_hosts: list[str] | None = None) -> None:
   """SCP this script to the remote host then run it there via SSH."""
   script = pathlib.Path(__file__).resolve()
   remote_path = f"~/{script.name}"


   password = os.getenv("VPE_PASSWORD", "")
   sshpass_prefix: list[str] = []
   if password and not key:
       if not shutil.which("sshpass"):
           print("  [warn] VPE_PASSWORD set but sshpass not found; falling back to interactive prompt")
           print("         Install with: brew install sshpass")
       else:
           sshpass_prefix = ["sshpass", "-p", password]


   ssh_opts = ["-o", "StrictHostKeyChecking=no", "-o", "IdentitiesOnly=yes",
               "-o", "ServerAliveInterval=60", "-o", "ServerAliveCountMax=30",
               "-p", str(port)]
   if key:
       ssh_opts += ["-i", key]
   target = f"{user}@{host}"


   # read serial, rest_token, tenant_id, ui_hostname, and mtls paths from the VPE
   serial      = os.getenv("SERIAL", "")
   rest_token  = os.getenv("REST_TOKEN", REST_TOKEN)
   tenant_id   = os.getenv("TENANT_ID", TENANT_ID)
   ui_hostname = os.getenv("UI_HOSTNAME", UI_HOSTNAME)
   mtls_cert   = os.getenv("MTLS_CERT", MTLS_CERT)
   mtls_key    = os.getenv("MTLS_KEY",  MTLS_KEY)
   license_key = os.getenv("LICENSE_KEY", LICENSE_KEY)
   try:
       result = subprocess.run(
           sshpass_prefix + ["ssh"] + ssh_opts + [target,
               "cat /opt/ns/cloud/serial; echo '---';"
               "cat /opt/ns/cloud/rest_api_token.json; echo '---';"
               "ls /opt/ns/tenant/; echo '---';"
               "python3 -c \"import json; d=json.load(open('/opt/ns/cloud/sfconfig.json')); print(d.get('ui_hostname',''))\"; echo '---';"
               "test -f /opt/ns/cfg/client.pem && echo /opt/ns/cfg/client.pem || echo ''; echo '---';"
               "test -f /opt/ns/cfg/client.key && echo /opt/ns/cfg/client.key || echo ''; echo '---';"
               "python3 -c \""
               "import re; "
               "m = re.search(r'^license_key: (.+)', open('/opt/ns/cfg/cfgagent.conf').read(), re.MULTILINE); "
               "print(m.group(1).strip() if m else '')"
               "\"; echo '---'"],
           capture_output=True, text=True, check=True,
       )
       parts = result.stdout.strip().split("---")
       import json as _json
       if not serial and len(parts) >= 1:
           raw = parts[0].strip()
           try:
               serial = _json.loads(raw).get("serial", raw)
           except Exception:
               serial = raw
           if serial:
               print(f"  [remote] detected VPE serial: {serial}")
       if len(parts) >= 2:
           try:
               token = _json.loads(parts[1].strip()).get("rest-token", "")
               if token:
                   rest_token = token
                   print(f"  [remote] detected REST token from VPE")
           except Exception:
               pass
       if len(parts) >= 3 and os.getenv("TENANT_ID", "") == "":
           tid = parts[2].strip()
           if tid:
               tenant_id = tid
               print(f"  [remote] detected tenant ID: {tenant_id}")
       if len(parts) >= 4 and os.getenv("UI_HOSTNAME", "") == "":
           h = parts[3].strip()
           if h:
               ui_hostname = h
               print(f"  [remote] detected UI hostname: {ui_hostname}")
       if len(parts) >= 5 and not mtls_cert:
           c = parts[4].strip()
           if c:
               mtls_cert = c
               print(f"  [remote] detected mTLS cert: {mtls_cert}")
       if len(parts) >= 6 and not mtls_key:
           k = parts[5].strip()
           if k:
               mtls_key = k
               print(f"  [remote] detected mTLS key: {mtls_key}")
       if len(parts) >= 7 and not license_key:
           lk = parts[6].strip()
           if lk:
               license_key = lk
               print(f"  [remote] detected license key from VPE")
   except Exception:
       pass


   # --- build credential pool from extra --credential-host VPEs (if any) ---
   # The runner host's own (license, serial) is always pair[0]; additional VPEs
   # passed via --credential-host get appended. TC-19/TC-20 read CREDENTIAL_POOL
   # and round-robin VUs across pairs (each VU stays sticky to one pair).
   cred_pool: list[dict[str, str]] = []
   if license_key and (serial or SERIAL):
       cred_pool.append({"license": license_key, "serial": serial or SERIAL})
   for chost in credential_hosts or []:
       if chost == host:
           continue  # already added
       print(f"  [credentials] fetching license+serial from {chost}...")
       pair = _fetch_credentials_from_vpe(
           chost, user, key, port, sshpass_prefix, ssh_opts,
       )
       if pair:
           cred_pool.append(pair)
           print(f"  [credentials] {chost}: serial={pair['serial']}")
   credential_pool_json = json.dumps(cred_pool) if len(cred_pool) > 1 else ""
   if credential_pool_json:
       print(f"  [credentials] pool size: {len(cred_pool)} (multi-appliance simulation enabled)")


   # --- env vars to forward ---
   forward = {
       "GATEWAY_TAG":    GATEWAY_TAG,
       "GATEWAY_URL":    GATEWAY_URL,
       "CONTROLLER_URL": os.getenv("CONTROLLER_URL", "http://localhost:8080"),
       "REST_TOKEN":     rest_token,
       "UI_HOSTNAME":    ui_hostname,
       "TENANT_ID":      tenant_id,
       "SERIAL":         serial or SERIAL,
       "MTLS_CERT":      mtls_cert,
       "MTLS_KEY":       mtls_key,
       "LICENSE_KEY":    license_key,
       "CREDENTIAL_POOL": credential_pool_json,
   }


   # 1. copy script (scp uses -P uppercase for port)
   scp_opts = ["-o", "StrictHostKeyChecking=no", "-o", "IdentitiesOnly=yes",
               "-P", str(port)]
   if key:
       scp_opts += ["-i", key]
   print(f"  [remote] copying {script.name} → {target}:{remote_path}")
   scp_cmd = sshpass_prefix + ["scp"] + scp_opts + [str(script), f"{target}:{remote_path}"]
   subprocess.run(scp_cmd, check=True)


   # copy test data files if present alongside the script
   for data_file in ["nsdebug.tar", "nsdebug.ns.debug", "diagnostic-agent.log"]:
       local_data = script.parent / data_file
       if local_data.exists():
           print(f"  [remote] copying {data_file} → {target}:~/{data_file}")
           scp_data = sshpass_prefix + ["scp"] + scp_opts + [str(local_data), f"{target}:~/{data_file}"]
           subprocess.run(scp_data, check=True)


   # 2. ensure aiohttp is installed on the remote host
   print("  [remote] setting up dependencies...")
   sudo_prefix = f"echo {shlex.quote(password)} | sudo -S " if password else "sudo "
   install_cmd = (
       # bootstrap pip then install aiohttp system-wide (dedicated test VM)
       f"curl -sSL https://bootstrap.pypa.io/get-pip.py -o /tmp/get-pip.py && "
       f"{sudo_prefix}python3 /tmp/get-pip.py --break-system-packages -q --root-user-action=ignore && "
       f"{sudo_prefix}python3 -m pip install --break-system-packages -q --root-user-action=ignore aiohttp"
   )
   subprocess.run(sshpass_prefix + ["ssh"] + ssh_opts + [target, install_cmd], check=True)


   # 2.5. Start kubectl port-forward on remote for TC-15/TC-17 (controller is in-cluster)
   needs_port_forward = any(tc in scenarios for tc in ["TC-15", "TC-17"])
   pf_pid: str | None = None
   if needs_port_forward:
       print("  [remote] starting kubectl port-forward svc/callhome-gateway-controller 8080:8080 ...")
       pf_cmd = "kubectl -n risk-insights port-forward svc/callhome-gateway-controller 8080:8080 &>/dev/null & echo $!"
       pf_result = subprocess.run(
           sshpass_prefix + ["ssh"] + ssh_opts + [target, pf_cmd],
           capture_output=True, text=True,
       )
       pf_pid = pf_result.stdout.strip()
       if pf_pid and pf_pid.isdigit():
           print(f"  [remote] port-forward started (PID {pf_pid}), waiting 3s for it to bind...")
           time.sleep(3)
       else:
           print("  [warn] could not start kubectl port-forward; TC-15/TC-17 will likely fail")
           pf_pid = None


   # 3. run remotely
   env_str = " ".join(
       f"{k}={shlex.quote(v)}" for k, v in forward.items() if v
   )
   tc_args = " ".join(scenarios)
   remote_cmd = f"{env_str} python3 {remote_path} {tc_args}"
   print(f"  [remote] running on {target}: {remote_cmd}\n")
   ssh_cmd = sshpass_prefix + ["ssh"] + ssh_opts + [target, remote_cmd]
   try:
       subprocess.run(ssh_cmd, check=True)
   finally:
       if pf_pid:
           subprocess.run(
               sshpass_prefix + ["ssh"] + ssh_opts + [target, f"kill {pf_pid} 2>/dev/null || true"],
               capture_output=True,
           )
           print(f"  [remote] port-forward (PID {pf_pid}) stopped")


   # 4. copy results back to local perf-runs/
   print("  [remote] copying perf-runs/ back to local machine...")
   local_perf_runs = pathlib.Path(__file__).parent / "perf-runs"
   local_perf_runs.mkdir(exist_ok=True)
   scp_back_cmd = (
       sshpass_prefix
       + ["scp"] + scp_opts
       + ["-r", f"{target}:~/perf-runs/.", str(local_perf_runs)]
   )
   r = subprocess.run(scp_back_cmd, check=False)
   if r.returncode == 0:
       print(f"  [remote] results saved to {local_perf_runs}")
   else:
       print(f"  [warn] SCP back failed (exit {r.returncode}). Recover manually:")
       print(f"         sshpass -p $VPE_PASSWORD scp -r {target}:~/perf-runs/. {local_perf_runs}")




